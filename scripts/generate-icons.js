function svgStroke(name, def) {
    const paths = def.paths.map((d) => `<path d="${d}"/>`).join('');
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="${def.stroke}" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" role="img" aria-hidden="true">${paths}</svg>`;
}

function svgFill(name, def) {
    const vb = def.viewBox || '0 0 24 24';
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="24" height="24" role="img" aria-hidden="true"><path fill="${def.fill}" d="${def.path}"/></svg>`;
}

